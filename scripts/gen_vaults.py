#!/usr/bin/env python3
"""Generate src/vaults_registry.rs: vault_config PDA -> (vault_id, supply mint, borrow mint, vault_type)
from the on-chain VaultConfig accounts of the Jupiter Lend vaults program (getProgramAccounts).
Older vault program versions did not emit LogUserPosition/LogLiquidateInfo, so this map is how
vault ids are attached to historical operations and liquidations. Newer vaults are also resolved
at runtime from the vault_id carried by their events."""
import json,base64,urllib.request,sys
RPC=sys.argv[1] if len(sys.argv)>1 else 'https://api.mainnet-beta.solana.com'
import hashlib
disc=hashlib.sha256(b'account:VaultConfig').digest()[:8]
ALPH='123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz'
def b58(b):
    n=int.from_bytes(b,'big');s=''
    while n: n,r=divmod(n,58);s=ALPH[r]+s
    return '1'*(len(b)-len(b.lstrip(b'\0')))+s
req={'jsonrpc':'2.0','id':1,'method':'getProgramAccounts','params':['jupr81YtYssSyPt8jbnGuiWon5f6x9TcDEFxYe3Bdzi',{'encoding':'base64','filters':[{'memcmp':{'offset':0,'bytes':b58(disc)}}]}]}
r=json.load(urllib.request.urlopen(urllib.request.Request(RPC,json.dumps(req).encode(),{'content-type':'application/json'})))['result']
rows=[]
for x in r:
    b=base64.b64decode(x['account']['data'][0])
    assert b[:8]==disc and len(b)>=219
    vid=int.from_bytes(b[8:10],'little');vtype=b[25]
    rows.append((vid,x['pubkey'],b58(b[154:186]),b58(b[186:218]),vtype))
rows.sort()
o=['// @generated by scripts/gen_vaults.py from on-chain VaultConfig accounts. Do not edit.',
   f'// {len(rows)} vaults.','','/// (vault_config, vault_id, supply_mint, borrow_mint, vault_type)',
   'pub const VAULTS: &[(&str, u32, &str, &str, u32)] = &[']
for v,p,s,bm,t in rows: o.append(f'    ("{p}", {v}, "{s}", "{bm}", {t}),')
o+=['];','','pub fn by_config(cfg: &str) -> Option<(u32, &\'static str, &\'static str, u32)> {',
    '    VAULTS.iter().find(|v| v.0 == cfg).map(|v| (v.1, v.2, v.3, v.4))','}','']
open('src/vaults_registry.rs','w').write('\n'.join(o));print(len(rows),'vaults')
