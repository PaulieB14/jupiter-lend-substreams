#!/usr/bin/env python3
"""Generate src/idl.rs (event + instruction discriminators and instruction account names)
from the official Jupiter Lend Anchor IDLs (github.com/jup-ag/jupiter-lend target/idl/*.json).
Discriminators are taken verbatim from the IDL and cross-checked against sha256("event:<Name>")
/ sha256("global:<name>")."""
import json,hashlib,sys,os
IDL=sys.argv[1] if len(sys.argv)>1 else 'idl'
progs=[('LIQUIDITY','liquidity'),('LENDING','lending'),('VAULTS','vaults'),('REWARDS','lending_reward_rate_model'),('FLASHLOAN','flashloan'),('DEX','dex')]
def snake_up(n):
    import re
    return re.sub(r'(?<!^)(?=[A-Z])','_',n).upper()
out=['// @generated by scripts/gen_idl.py from the official Jupiter Lend IDLs. Do not edit.','#![allow(dead_code)]','']
for const,f in progs:
    d=json.load(open(f'{IDL}/{f}.json'))
    out.append(f'pub const {const}_PROGRAM: &str = "{d["address"]}";')
out.append('')
for const,f in progs:
    d=json.load(open(f'{IDL}/{f}.json'))
    out.append(f'pub mod {f} {{')
    for e in d.get('events',[]):
        disc=e['discriminator'];assert list(hashlib.sha256(('event:'+e['name']).encode()).digest()[:8])==disc
        out.append(f'    pub const EV_{snake_up(e["name"])}: [u8; 8] = {disc};')
    out.append('    /// (instruction discriminator, instruction name, account names in IDL order)')
    out.append('    pub const INSTRUCTIONS: &[([u8; 8], &str, &[&str])] = &[')
    for i in d['instructions']:
        disc=i['discriminator'];assert list(hashlib.sha256(('global:'+i['name']).encode()).digest()[:8])==disc
        accs=', '.join(f'"{a["name"]}"' for a in i['accounts'])
        out.append(f'        ({disc}, "{i["name"]}", &[{accs}]),')
    out.append('    ];')
    out.append('}')
    out.append('')
open('src/idl.rs','w').write('\n'.join(out))
